/**
 * 文字サイズの規格。
 *
 * 段階は5つだけ。1.2〜1.25倍の比で上がる（12 → 14 → 16 → 20 → 24）。
 * 名前は「どこで使うか」で付ける。用途が決まらない中間の値は作らない。
 *
 * **12px を下回る段階は作らない。** 以前は 9/10/11px の段階があり、
 * 実測で51種の文字が12px未満だった。可読性の指針はいずれも12pxを下限としている:
 *
 * | 基準 | 下限 |
 * |---|---|
 * | Apple HIG | 11pt |
 * | Material Design | 12sp（caption が最小） |
 * | GOV.UK / BBC GEL | 本文16px・補助14px・絶対下限12px |
 *
 * WCAG 2.2 に絶対値の規定は無いが、上のどれも下回っていた。
 */
export const FS = {
  /** 補助テキスト・バッジ・件数・小さなボタン。これが最小 */
  caption: '12px',
  /** 標準テキスト・ボタン・路線名・一覧の項目 */
  body: '14px',
  /**
   * 見出し、および入力欄。
   *
   * 入力欄がこの段階なのは iOS Safari 対策。16px 未満の入力欄に
   * フォーカスするとページを自動拡大するため、下回らせない。
   */
  input: '16px',
  /** 節の見出しと同じ大きさ。入力欄と揃える */
  title: '16px',
  /** 強調した数値（所要時間の分数など）・ダイアログの見出し */
  heading: '20px',
  /** 最上位の見出し */
  display: '24px',
} as const;

/**
 * インタラクティブ要素の最小サイズ (px)
 *
 * - WCAG 2.2 AA の達成基準 2.5.8「ターゲットサイズ(最小)」は 24×24 が下限
 * - Apple HIG は 44×44pt、Material Design は 48×48dp をタッチ操作の推奨値とする
 *   ため、指で操作するモバイルでは 44px を目標にする
 */
export const TARGET = {
  /** WCAG 2.2 AA の絶対下限。ポインタ操作のデスクトップはこれで足りる */
  min: 24,
  /** タッチ操作時の推奨値 (Apple HIG 44pt) */
  touch: 44,
} as const;

/**
 * 意味を持つ色の単一定義。
 *
 * 「出発は緑・到着は赤」はアプリ全体の約束事なのに、これまで12ファイルが
 * 各自 `#4CAF50` と書いていて、色を変えるには全部直す必要があった。
 * 実際に入力欄だけ色が変わってボタンが取り残される事故が起きている。
 *
 * 新しく書くコードは必ずここから取る。既存のベタ書きは触る箇所から置き換える。
 * 詳細は docs/design-system.md を参照。
 */
export const SEMANTIC = {
  /** 出発駅・確定・OK */
  departure: '#4CAF50',
  /** 到着駅・警告 */
  arrival: '#F44336',
  /** 選択中・リンクなどの主色 */
  primary: '#2196F3',
} as const;

/**
 * 白と黒の唯一の定義。
 *
 * `color: 'white'` `'#fff'` `'#ffffff'` が76箇所に散らばっていて、
 * 同じ「塗った色の上に載せる文字」を各ファイルが別々の書き方で持っていた
 * （`white` / `#fff` / `#ffffff` の3通りが混在し、検索でも取りこぼしていた）。
 *
 * UIの文字色・背景・境界線は原則 `getThemeColors(theme)` から取ること。
 * ここを直接使ってよいのは、テーマではなく「下の色」で決まる場合だけ:
 * 路線色で塗ったボタンやチップの上に載せる文字、地図ラベルの縁取りなど。
 * その場合も、コントラスト判定が要るなら `filledLabelColors()` を使う。
 */
export const NEUTRAL = {
  white: '#ffffff',
  black: '#000000',
} as const;

/**
 * 白・黒に不透明度をかけた色。
 *
 * `rgba(255,255,255,0.8)` のような直書きが散らばると、
 * 「白の半透明」を変えたいときに全部を探して直すことになる。
 */
export const alphaWhite = (alpha: number) => `rgba(255, 255, 255, ${alpha})`;
export const alphaBlack = (alpha: number) => `rgba(0, 0, 0, ${alpha})`;

